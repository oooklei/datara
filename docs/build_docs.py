def _set_font(style_or_run, name, size=None, bold=None, color=None):
    f = style_or_run.font
    f.name = name
    if size is not None:
        f.size = Pt(size)
    if bold is not None:
        f.bold = bold
    if color is not None:
        f.color.rgb = color
    rpr = style_or_run.element.get_or_add_rPr()
    rf = rpr.get_or_add_rFonts()
    for attr in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
        rf.set(qn(attr), name)


def new_doc():
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Mm(210), Mm(297)
    sec.top_margin = sec.bottom_margin = Cm(2.5)
    sec.left_margin = sec.right_margin = Cm(2.2)
    _set_font(doc.styles['Normal'], '宋体', size=10.5)
    doc.styles['Normal'].paragraph_format.line_spacing = 1.3
    for i in range(1, 5):
        st = doc.styles['Heading %d' % i]
        _set_font(st, '黑体', size={1: 16, 2: 13, 3: 12, 4: 11}[i], bold=True, color=RGBColor(0, 0, 0))
        st.paragraph_format.space_before = Pt(10)
        st.paragraph_format.space_after = Pt(4)
    return doc


def H(doc, level, text):
    doc.add_heading(text, level=level)


def P(doc, text, bold=False, kai=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _set_font(r, '楷体' if kai else '宋体', bold=bold or None)
    return p


def NOTE(doc, text):
    p = doc.add_paragraph()
    r = p.add_run('〔说明〕' + text)
    _set_font(r, '楷体', size=10)
    return p


def T(doc, headers, rows, widths=None):
    tb = doc.add_table(rows=1, cols=len(headers))
    tb.style = 'Table Grid'
    tb.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        cell = tb.rows[0].cells[j]
        cell.text = ''
        r = cell.paragraphs[0].add_run(h)
        _set_font(r, '黑体', size=9.5, bold=True)
    for row in rows:
        cells = tb.add_row().cells
        for j, v in enumerate(row):
            cells[j].text = ''
            r = cells[j].paragraphs[0].add_run(str(v))
            _set_font(r, '宋体', size=9.5)
    if widths:
        for j, w in enumerate(widths):
            for row in tb.rows:
                row.cells[j].width = Cm(w)
    doc.add_paragraph()
    return tb


def cover(doc, title, ver, date, status):
    for _ in range(5):
        doc.add_paragraph()
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run('Datara 数据治理工具'); _set_font(r, '黑体', size=24, bold=True)
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(title); _set_font(r, '黑体', size=26, bold=True)
    for _ in range(6):
        doc.add_paragraph()
    T(doc, ['项目', '内容'], [
        ['文档版本', ver], ['发布日期', date], ['编制', 'Datara 项目组'],
        ['文档状态', status], ['适用系统', 'datara-web 数据治理工具（Vite + Vue 3）'],
    ], widths=[4, 10])
    doc.add_page_break()


