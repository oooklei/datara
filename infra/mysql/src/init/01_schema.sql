-- ============================================================
-- Datara 业务源库 ec_retail 建表（I2 设计文档 §4，4 域 14 表 + 3 机密表）
-- 载体：mysql-src 容器 /docker-entrypoint-initdb.d（首启自动执行）+ install/reset 幂等重放
-- 幂等：CREATE TABLE IF NOT EXISTS
-- 约束：逻辑外键、不建物理 FK（脏数据矩阵含引用断裂/孤儿行，物理 FK 会拒收）；
--       外键关系声明在 datara-backend/tools/datagen/tables.yaml relations
-- 分区：3 张交易大表按天 RANGE 90 天 + pmax 兜底（共 91 分区）；边界为设计窗口
--       T=2026-09-18，生成器 gen 每次按运行日 T 重算滚动（REORGANIZE PARTITION）
--       分区表主键为复合键（id + 分区列）：MySQL 要求 PK/UNIQUE 必须包含分区列
-- 密级：sec_* 三表为机密/绝密实证位（安全权限后置另立，数据先行）
-- ============================================================
SET NAMES utf8mb4;

-- ================= 用户域 =================

-- 1. dim_user 用户维表（敏感明文植入位：phone/id_card）
CREATE TABLE IF NOT EXISTS dim_user (
  id            INT          NOT NULL COMMENT '用户ID',
  username      VARCHAR(64)  NOT NULL COMMENT '登录名',
  real_name     VARCHAR(64)  NULL COMMENT '真实姓名',
  phone         VARCHAR(20)  NULL COMMENT '手机号（敏感明文；含格式错样本）',
  id_card       VARCHAR(18)  NULL COMMENT '身份证号（敏感明文）',
  nickname      VARCHAR(64)  NULL COMMENT '昵称（空值脏样本）',
  age           INT          NULL COMMENT '年龄（越界脏样本 255）',
  gender        CHAR(1)      NULL COMMENT '性别 M/F',
  city          VARCHAR(64)  NULL COMMENT '城市',
  user_level    TINYINT      NULL COMMENT '会员等级 1-5',
  register_time DATETIME     NULL COMMENT '注册时间',
  PRIMARY KEY (id),
  KEY idx_dim_user_phone (phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户维表';

-- 2. dim_user_address 收货地址
CREATE TABLE IF NOT EXISTS dim_user_address (
  id             INT          NOT NULL,
  user_id        INT          NOT NULL COMMENT 'FK dim_user.id',
  province       VARCHAR(32)  NULL,
  city           VARCHAR(32)  NULL,
  district       VARCHAR(32)  NULL,
  detail         VARCHAR(255) NULL COMMENT '详细地址（脏字符样本）',
  receiver_name  VARCHAR(64)  NULL,
  receiver_phone VARCHAR(20)  NULL,
  is_default     TINYINT      NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY idx_ua_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='收货地址';

-- 3. ods_cart 购物车（重复记录脏样本：连续双行同内容）
CREATE TABLE IF NOT EXISTS ods_cart (
  id       INT      NOT NULL,
  user_id  INT      NOT NULL COMMENT 'FK dim_user.id',
  goods_id INT      NOT NULL COMMENT 'FK dim_goods.id',
  qty      INT      NOT NULL DEFAULT 1,
  add_time DATETIME NULL COMMENT '加购时间（时间异常样本）',
  status   TINYINT  NOT NULL DEFAULT 0 COMMENT '0未付/1已付/2失效/3删除（枚举外样本 9）',
  PRIMARY KEY (id),
  KEY idx_cart_user (user_id),
  KEY idx_cart_goods (goods_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='购物车流水';

-- ================= 商品域 =================

-- 4. dim_category 商品类目（自关联）
CREATE TABLE IF NOT EXISTS dim_category (
  id            INT         NOT NULL,
  category_name VARCHAR(64) NULL COMMENT '类目名（脏字符样本）',
  parent_id     INT         NULL COMMENT '父类目 id（顶级为 NULL）',
  level         TINYINT     NOT NULL DEFAULT 1,
  sort_order    INT         NOT NULL DEFAULT 0,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品类目';

-- 5. dim_supplier 供应商（三规则实证位：企业信用代码）
CREATE TABLE IF NOT EXISTS dim_supplier (
  id             INT          NOT NULL,
  supplier_name  VARCHAR(128) NULL COMMENT '供应商名称',
  credit_code    VARCHAR(18)  NULL COMMENT '统一社会信用代码（三规则实证位；含格式错样本）',
  contact_person VARCHAR(64)  NULL,
  contact_phone  VARCHAR(20)  NULL,
  address        VARCHAR(255) NULL,
  status         TINYINT      NOT NULL DEFAULT 1,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供应商';

-- 6. dim_goods 商品
CREATE TABLE IF NOT EXISTS dim_goods (
  id          INT           NOT NULL,
  goods_name  VARCHAR(128)  NULL COMMENT '商品名（脏字符样本）',
  category_id INT           NOT NULL COMMENT 'FK dim_category.id',
  supplier_id INT           NOT NULL COMMENT 'FK dim_supplier.id',
  price       DECIMAL(10,2) NULL COMMENT '售价（负数越界样本）',
  cost_price  DECIMAL(10,2) NULL COMMENT '成本价',
  status      TINYINT       NOT NULL DEFAULT 1 COMMENT '1在售/0下架',
  shelf_time  DATETIME      NULL,
  PRIMARY KEY (id),
  KEY idx_goods_cat (category_id),
  KEY idx_goods_supplier (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品维表';

-- 7. dim_inventory 库存快照
CREATE TABLE IF NOT EXISTS dim_inventory (
  id             INT          NOT NULL,
  goods_id       INT          NOT NULL COMMENT 'FK dim_goods.id',
  warehouse_code VARCHAR(16)  NULL COMMENT '仓库编码 WH01-WH05',
  qty            INT          NULL COMMENT '库存量（负数越界样本）',
  snapshot_date  DATE         NOT NULL COMMENT '快照日期',
  PRIMARY KEY (id),
  KEY idx_inv_goods (goods_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='库存快照';

